import { chromium } from "playwright";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(`${process.env.BASE_URL || "http://127.0.0.1:3000"}/`, { waitUntil: "networkidle" });
await page.screenshot({ path: "/tmp/chips-desktop.png", fullPage: true });
assert.equal(await page.getByTestId("snack-card").count(), 4);
await page.getByRole("button", { name: "◒ Chips", exact: true }).click();
assert.equal(await page.getByTestId("snack-card").count(), 1);
await page.getByRole("button", { name: "All snacks", exact: true }).click();
await page.getByLabel("Search snacks").fill("no such snack");
await page.getByText("No crumbs here.").waitFor();
await page.getByRole("button", { name: "See all snacks" }).click();
await page.getByRole("button", { name: "Add to bag" }).first().click();
await page.getByRole("button", { name: "Open shopping bag, 1 items" }).click();
await page.getByRole("button", { name: "Add one The chocolate chip", exact: true }).click();
await page.getByText("Your bag (2)", { exact: true }).waitFor();
await page.getByRole("button", { name: "Close shopping bag" }).click();
await page.reload({ waitUntil: "networkidle" });
await page.getByRole("button", { name: "Open shopping bag, 2 items" }).click();
await page.getByRole("button", { name: "Preview order confirmation" }).click();
await page.getByText("No payment was taken and no order was placed.", { exact: false }).waitFor();
await page.getByRole("button", { name: "Keep exploring" }).click();
await page.getByRole("button", { name: "View The chocolate chip", exact: true }).click();
await page.getByRole("dialog").waitFor();
await page.keyboard.press("Escape");
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: "/tmp/chips-mobile.png", fullPage: true });
assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "mobile overflow");
await page.getByRole("button", { name: "Open shopping bag, 2 items" }).click();
await page.getByRole("button", { name: "Remove", exact: true }).click();
await page.getByText("Your next happy snack is waiting.").waitFor();
await page.keyboard.press("Escape");
await page.goto(`${process.env.BASE_URL || "http://127.0.0.1:3000"}/shop`, { waitUntil: "networkidle" });
assert.equal(new URL(page.url()).pathname, "/");
assert.deepEqual(errors, []);
console.log("PASS: catalogue filters, search empty state, add/update/remove, reload persistence, preview confirmation, product modal, mobile overflow, sample shop redirect, no browser errors.");
await browser.close();
